/**
 * Generates the MySQL/MariaDB schema (prisma/mysql/schema) from the SQLite schema (prisma/schema), which stays the
 * single source of truth (D-98). The web deployment (Vercel + Hostinger MySQL) uses the MySQL schema; the office
 * install and the test suite keep SQLite.
 *
 * Differences applied:
 *  - provider "mysql" and its own client output (generated/prisma-mysql);
 *  - String fields become TEXT (`@db.Text`) unless they are ids, unique, indexed or foreign keys, which stay
 *    VARCHAR(191) so they can be indexed. SQLite has no length limit, so free text must not be cut at 191.
 *
 * Usage: tsx scripts/mysql-schema.ts          (write)
 *        tsx scripts/mysql-schema.ts --check  (exit 1 if the committed MySQL schema is out of date)
 */
import fs from "node:fs";
import path from "node:path";

const SRC = "prisma/schema";
const OUT = "prisma/mysql/schema";

function convert(file: string, text: string): string {
  if (file === "schema.prisma") {
    text = text
      .replace('output   = "../../generated/prisma"', 'output   = "../../../generated/prisma-mysql"')
      .replace('provider = "sqlite"', 'provider = "mysql"')
      .replace(/^\/\/ QEPEX India Work Tracker — Prisma schema \(multi-file\)\./m, "// GENERATED by scripts/mysql-schema.ts from prisma/schema — do not edit. MySQL/MariaDB variant (D-98).");
  }
  // Model by model: find the String fields that must stay indexable.
  return text.replace(/model (\w+) \{([\s\S]*?)\n\}/g, (block, _name: string, body: string) => {
    const keep = new Set<string>();
    for (const m of body.matchAll(/@relation\([^)]*fields:\s*\[([^\]]+)\]/g)) m[1]!.split(",").forEach((f) => keep.add(f.trim()));
    for (const m of body.matchAll(/@@(?:unique|index|id)\(\[([^\]]+)\]/g)) m[1]!.split(",").forEach((f) => keep.add(f.trim().split("(")[0]!.trim()));
    const lines = body.split("\n").map((line) => {
      const f = /^(\s+)(\w+)(\s+)String(\??)(.*)$/.exec(line);
      if (!f) return line;
      const [, indent, name, gap, opt, rest] = f;
      if (keep.has(name!) || /@id\b|@unique\b|@db\./.test(rest!)) return line;
      // Keep any trailing comment after the attributes.
      const c = rest!.indexOf("//");
      const attrs = c >= 0 ? rest!.slice(0, c).trimEnd() : rest!.trimEnd();
      const comment = c >= 0 ? ` ${rest!.slice(c)}` : "";
      return `${indent}${name}${gap}String${opt}${attrs} @db.Text${comment}`;
    });
    return `model ${_name} {${lines.join("\n")}\n}`;
  });
}

const check = process.argv.includes("--check");
let stale = false;
fs.mkdirSync(OUT, { recursive: true });
for (const file of fs.readdirSync(SRC).filter((f) => f.endsWith(".prisma")).sort()) {
  const out = convert(file, fs.readFileSync(path.join(SRC, file), "utf8"));
  const target = path.join(OUT, file);
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null;
  if (current === out) continue;
  if (check) {
    console.error(`out of date: ${target}`);
    stale = true;
  } else fs.writeFileSync(target, out);
}
if (check && stale) {
  console.error("Run: npm run db:mysql-schema");
  process.exit(1);
}
if (!check) console.log(`MySQL schema written to ${OUT}`);

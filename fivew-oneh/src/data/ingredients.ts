// "glossary" records exist mainly so the ingredient-list analyser can explain
// common formulation ingredients. Concentrations are only stated where they are
// widely documented by regulators or professional bodies.

const R = '2026-10-15';

function glossary(
  id: string,
  name: string,
  synonyms: string[],
  kind: string,
  functions: string[],
  summary: string,
  extra: Partial<Ingredient> = {},
): Ingredient {
  return {
    id,
    name,
    synonyms,
    kind,
    functions,
    productTypes: extra.productTypes ?? [],
    categories: extra.categories ?? ['ingredients'],
    tier: 'glossary',
    summary,
    evidence: extra.evidence ?? { level: 'established', summary: 'Widely used formulation ingredient with a well-understood function.' },
    sources: extra.sources ?? ['cosing', 'carelens-editorial'],
    lastReviewed: extra.lastReviewed ?? R,
    status: extra.status ?? 'published',
    ...extra,
  };
}


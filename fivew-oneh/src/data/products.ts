import type { Product, ProductIngredient, SuitabilityTags } from './types';
import { declaredConcentration, matchIngredient, splitIngredientList } from '../lib/ingredientMatch';

// IMPORTANT: every product below is a FICTIONAL DEMONSTRATION RECORD.
// Brands carry the "DemoLab" prefix, prices are illustrative, and formulations
// are representative examples — not real products. They exist so search,
// comparison and the analyser can be exercised without inventing data about
// real brands. Replace with verified records via the content workflow (README).

function parse(list: string): ProductIngredient[] {
  return splitIngredientList(list).map((label) => ({
    ingredientId: matchIngredient(label)?.ingredient.id ?? null,
    label,
    concentration: declaredConcentration(label),
  }));
}

interface DemoInput {
  id: string;
  name: string;
  brand: string;
  category: string;
  subcategory: string;
  productType: string;
  intendedUse: string;
  description: string;
  list: string;
  qty: [number, 'ml' | 'g'];
  price: number;
  directions: string;
  suitability?: SuitabilityTags;
  benefits?: string[];
  limitations?: string[];
  warnings?: string[];
}

function demo(p: DemoInput): Product {
  return {
    id: p.id,
    name: p.name,
    brand: p.brand,
    category: p.category,
    subcategory: p.subcategory,
    productType: p.productType,
    intendedUse: p.intendedUse,
    description: p.description,
    ingredients: parse(p.list),
    ingredientListVerified: false,
    netQuantity: { value: p.qty[0], unit: p.qty[1] },
    price: { amount: p.price, currency: 'INR', verified: false },
    directions: p.directions,
    suitability: p.suitability,
    benefits: p.benefits,
    limitations: p.limitations,
    warnings: p.warnings ?? ['For external use only.', 'Patch test before first use.'],
    sources: ['carelens-editorial'],
    demo: true,
    verification: 'unverified',
    lastVerified: '2026-10-20',
    status: 'published',
  };
}


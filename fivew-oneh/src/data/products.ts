/** Price per standard unit (₹ per 100 ml/g, and per ml/g). */
export function unitPrice(p: Product): { per100: number; perUnit: number; unit: string } | null {
  if (!p.price || !p.netQuantity.value) return null;
  const perUnit = p.price.amount / p.netQuantity.value;
  return { perUnit, per100: perUnit * 100, unit: p.netQuantity.unit };
}

/** Share of key fields that are present — a simple, transparent completeness measure. */
export function completeness(p: Product): { score: number; missing: string[] } {
  const checks: [string, boolean][] = [
    ['Ingredient list', p.ingredients.length > 0],
    ['Verified ingredient list', p.ingredientListVerified],
    ['Net quantity', !!p.netQuantity.value],
    ['Price', !!p.price],
    ['Verified price', !!p.price?.verified],
    ['Directions', !!p.directions],
    ['Warnings', !!p.warnings?.length],
    ['Official URL', !!p.officialUrl],
  ];
  const missing = checks.filter(([, ok]) => !ok).map(([k]) => k);
  return { score: Math.round(((checks.length - missing.length) / checks.length) * 100), missing };
}

// Generates db/seed.sql from the typed content in src/data (the single source of truth).
// Usage: npm run db:seed-sql
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ARTICLES } from '../src/data/articles';
import { CATEGORIES } from '../src/data/categories';
import { INGREDIENTS } from '../src/data/ingredients';
import { PRODUCTS } from '../src/data/products';
import { REGIONS } from '../src/data/regions';
import { SOURCES } from '../src/data/sources';
import { TOPICS } from '../src/data/topics';
import { QUERY_SYNONYMS } from '../src/lib/search';

/** Marks a value for a jsonb column (plain arrays are otherwise written as text[]). */
class Json {
  constructor(readonly v: unknown) {}
}
const json = (v: unknown) => new Json(v);

const q = (v: unknown): string => {
  if (v === undefined || v === null) return 'null';
  if (v instanceof Json) return `${q(JSON.stringify(v.v ?? null))}::jsonb`;
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (Array.isArray(v)) return v.length ? `array[${v.map(q).join(', ')}]::text[]` : `'{}'::text[]`;
  if (typeof v === 'object') return `${q(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const row = (table: string, cols: Record<string, unknown>) =>
  `insert into ${table} (${Object.keys(cols).join(', ')}) values (${Object.values(cols).map(q).join(', ')});`;

export function generateSeedSql(): string {
  const out: string[] = ['-- Generated by scripts/generate-seed-sql.ts — do not edit by hand.', 'begin;'];

  for (const s of SOURCES) out.push(row('sources', { id: s.id, title: s.title, publisher: s.publisher, url: s.url, kind: s.kind, note: s.note }));
  CATEGORIES.forEach((c, i) => {
    out.push(row('categories', { id: c.id, name: c.name, short_name: c.short, description: c.description, icon: c.icon, sort_order: i }));
    c.subcategories.forEach((s, j) => out.push(row('subcategories', { category_id: c.id, id: s.id, name: s.name, description: s.description, sort_order: j })));
  });
  for (const r of REGIONS) out.push(row('regions', { id: r.id, name: r.name, state: r.state, climate: r.climate, lat: r.lat, lon: r.lon, note: r.note }));
  for (const [re, rep] of QUERY_SYNONYMS) out.push(row('search_synonyms', { pattern: re.source.replace(/\\b/g, ''), replacement: rep }));

  for (const i of INGREDIENTS) {
    const { benefits, limitations, adverseEffects, precautions, compatibility, applications, forms, misconceptions, faqs } = i;
    out.push(
      row('ingredients', {
        id: i.id, name: i.name, inci: i.inci, kind: i.kind, tier: i.tier, summary: i.summary, functions: i.functions, product_types: i.productTypes,
        evidence_level: i.evidence.level, evidence_summary: i.evidence.summary, concentrations: i.concentrations, traditional_use: i.traditionalUse,
        flags: i.flags ?? [], details: { benefits, limitations, adverseEffects, precautions, compatibility, applications, forms, misconceptions, faqs },
        five_w: i.fiveW ?? null, suitability: i.suitability ?? {}, status: i.status, last_reviewed: i.lastReviewed,
      }),
    );
    for (const s of new Set(i.synonyms)) out.push(row('ingredient_synonyms', { ingredient_id: i.id, synonym: s }));
    for (const c of i.categories) out.push(row('ingredient_categories', { ingredient_id: i.id, category_id: c }));
    for (const s of i.sources) out.push(row('ingredient_sources', { ingredient_id: i.id, source_id: s }));
  }
  for (const i of INGREDIENTS) for (const a of i.alternatives ?? []) out.push(row('ingredient_alternatives', { ingredient_id: i.id, alternative_id: a }));

  const brands = new Map(PRODUCTS.map((p) => [p.brand, p.demo]));
  const brandId = (name: string) => name.toLowerCase().replace(/[^a-z0-9]+/g, '-');
  for (const [name, demo] of brands) out.push(row('brands', { id: brandId(name), name, is_demo: demo }));
  for (const p of PRODUCTS) {
    out.push(
      row('products', {
        id: p.id, brand_id: brandId(p.brand), name: p.name, category_id: p.category, subcategory_id: p.subcategory, product_type: p.productType,
        intended_use: p.intendedUse, description: p.description, net_quantity_value: p.netQuantity.value, net_quantity_unit: p.netQuantity.unit,
        price_amount: p.price?.amount, price_currency: p.price?.currency ?? 'INR', price_verified: p.price?.verified ?? false, directions: p.directions,
        details: { benefits: p.benefits, limitations: p.limitations, warnings: p.warnings }, suitability: p.suitability ?? {}, official_url: p.officialUrl,
        is_demo: p.demo, ingredient_list_verified: p.ingredientListVerified, verification: p.verification, status: p.status, last_verified: p.lastVerified,
      }),
    );
    p.ingredients.forEach((pi, idx) => out.push(row('product_ingredients', { product_id: p.id, position: idx + 1, label: pi.label, ingredient_id: pi.ingredientId, concentration: pi.concentration })));
    for (const s of p.sources) out.push(row('product_sources', { product_id: p.id, source_id: s }));
  }

  for (const t of TOPICS) {
    out.push(
      row('care_topics', {
        id: t.id, name: t.name, kind: t.kind, subcategory_id: t.subcategory, summary: t.summary, synonyms: t.synonyms, traditional_purpose: t.traditionalPurpose,
        recommendation: t.recommendation, claims: json(t.claims ?? []), details: { risks: t.risks, hygiene: t.hygiene, precautions: t.precautions, seeProfessional: t.seeProfessional, faqs: t.faqs, misconceptions: t.misconceptions },
        five_w: t.fiveW, suitability: t.suitability ?? {}, status: t.status, last_reviewed: t.lastReviewed,
      }),
    );
    for (const c of t.categories) out.push(row('topic_categories', { topic_id: t.id, category_id: c }));
    for (const r of t.relatedIngredients ?? []) out.push(row('topic_relationships', { topic_id: t.id, related_type: 'ingredient', related_id: r }));
    for (const r of t.relatedTopics ?? []) out.push(row('topic_relationships', { topic_id: t.id, related_type: 'topic', related_id: r }));
    for (const s of t.sources) out.push(row('topic_sources', { topic_id: t.id, source_id: s }));
  }

  for (const a of ARTICLES) {
    out.push(
      row('articles', {
        id: a.id, title: a.title, type: a.type, summary: a.summary, takeaways: a.takeaways, sections: json(a.sections), keywords: a.keywords,
        read_minutes: a.readMinutes, author: a.author, published_on: a.published, last_reviewed: a.lastReviewed, status: a.status,
      }),
    );
    for (const c of a.categories) out.push(row('article_categories', { article_id: a.id, category_id: c }));
    for (const r of a.relatedIngredients ?? []) out.push(row('article_relations', { article_id: a.id, related_type: 'ingredient', related_id: r }));
    for (const r of a.relatedTopics ?? []) out.push(row('article_relations', { article_id: a.id, related_type: 'topic', related_id: r }));
    for (const r of a.relatedProducts ?? []) out.push(row('article_relations', { article_id: a.id, related_type: 'product', related_id: r }));
    for (const s of a.sources) out.push(row('article_sources', { article_id: a.id, source_id: s }));
  }
  out.push('commit;', '');
  return out.join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const file = resolve(dirname(fileURLToPath(import.meta.url)), '../db/seed.sql');
  writeFileSync(file, generateSeedSql());
  console.log(`Wrote ${file}`);
}

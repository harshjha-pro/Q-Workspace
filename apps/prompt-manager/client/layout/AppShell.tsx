// ---------- Page meta (mobile title / back button) ----------
let meta: { title: string; back?: string | boolean } = { title: '' };
const mSubs = new Set<() => void>();
export function usePageMeta(title: string, back?: string | boolean) {
  useEffect(() => { meta = { title, back }; mSubs.forEach((s) => s()); document.title = title ? `${title} · Prompt Manager` : 'Prompt & Project Manager'; }, [title, back]);
}
const usePageMetaValue = () => useSyncExternalStore((l) => { mSubs.add(l); return () => mSubs.delete(l); }, () => meta);

// ---------- Quick actions (available everywhere) ----------
type QuickKind = 'project' | 'subproject' | 'prompt' | 'upload' | 'pack' | 'collection' | null;
let quick: { kind: QuickKind; projectId?: string } = { kind: null };
const qSubs = new Set<() => void>();
export const openQuick = (kind: QuickKind, projectId?: string) => { quick = { kind, projectId }; qSubs.forEach((s) => s()); };
const useQuick = () => useSyncExternalStore((l) => { qSubs.add(l); return () => qSubs.delete(l); }, () => quick);

function QuickHost() {
  const q = useQuick();
  const nav = useNavigate();
  const [target, setTarget] = useState('');
  const [category, setCategory] = useState<FileCategory>('reference');
  useStoreVersion();
  useEffect(() => { setTarget(q.projectId ?? (topProjects()[0]?.id || '')); }, [q]);
  const close = () => openQuick(null);
  if (q.kind === 'project') return <ProjectFormModal open onClose={close} onSaved={(p) => nav(`/p/${p.id}`)} />;
  if (q.kind === 'subproject') {
    if (!q.projectId) {
      const tops = topProjects();
      return (
        <Modal open onClose={close} title="Create subproject" footer={<><Button onClick={close}>Cancel</Button><Button variant="primary" disabled={!target} onClick={() => openQuick('subproject', target)}>Continue</Button></>}>
          {tops.length ? <Field label="Parent project"><select className="select" value={target} onChange={(e) => setTarget(e.target.value)}>{tops.map((p) => <option key={p.id} value={p.id}>{p.name}</option>)}</select></Field> : <p className="muted">Create a project first.</p>}
        </Modal>
      );
    }
    return <ProjectFormModal open onClose={close} parentId={q.projectId} onSaved={(p) => nav(`/p/${p.id}`)} />;
  }
  if (!q.kind) return null;
  const titles: Record<string, string> = { prompt: 'Add prompt', upload: 'Upload files', pack: 'Generate prompt pack', collection: 'New collection' };
  const go = () => {
    if (!target) return;
    close();
    if (q.kind === 'prompt') nav(`/p/${target}/prompts/new`);
    if (q.kind === 'upload') nav(`/p/${target}/files/${category}?upload=1`);
    if (q.kind === 'pack') nav(`/p/${target}/pack`);
    if (q.kind === 'collection') nav(`/p/${target}/collections?new=1`);
  };
  const hasProjects = topProjects(true).length > 0;
  return (
    <Modal open onClose={close} title={titles[q.kind]} footer={hasProjects ? <><Button onClick={close}>Cancel</Button><Button variant="primary" onClick={go} disabled={!target}>Continue</Button></> : <Button variant="primary" onClick={() => openQuick('project')}>Create a project</Button>}>
      {hasProjects ? (
        <>
          <Field label="Project or subproject" htmlFor="quick-target"><ProjectSelect id="quick-target" value={target} onChange={setTarget} /></Field>
          {q.kind === 'upload' && (
            <Field label="File category">
              <div className="radio-cards">
                {FILE_CATEGORIES.map((c) => <label key={c} className="radio-card"><input type="radio" name="cat" checked={category === c} onChange={() => setCategory(c)} /><span><span className="strong">{CATEGORY_LABEL[c]}</span><br /><span className="small muted">{c === 'reference' ? 'Permanent background material' : c === 'additional' ? 'Supporting attachments for specific tasks' : 'Documents generated by AI tools (versioned)'}</span></span></label>)}
              </div>
            </Field>
          )}
        </>
      ) : <p className="muted">You need a project before you can {q.kind === 'upload' ? 'upload files' : 'do this'}.</p>}
    </Modal>
  );
}

// ---------- Sync indicator ----------
function SyncPill({ compact }: { compact?: boolean }) {
  const s = useSyncStatus();
  const nav = useNavigate();
  let cls = 'ok', icon = <CheckCircle2 />, text = 'Synced';
  if (s.authRequired) { cls = 'err'; icon = <KeyRound />; text = 'Sign in to sync'; }
  else if (!s.online) { cls = 'offline'; icon = <CloudOff />; text = s.pending || s.uploads ? `Offline · ${s.pending + s.uploads} pending` : 'Offline'; }
  else if (s.syncing || s.pending || s.uploads) { cls = ''; icon = <RefreshCw className="spin" style={{ animation: 'spin 1s linear infinite' }} />; text = s.pending + s.uploads ? `Syncing ${s.pending + s.uploads}…` : 'Syncing…'; }
  else if (s.error) { cls = 'err'; icon = <AlertTriangle />; text = 'Sync issue'; }
  else if (s.conflicts) { cls = 'err'; icon = <GitMerge />; text = `${plural(s.conflicts, 'conflict')}`; }
  return (
    <button className={`sync-pill ${cls}`} onClick={() => nav('/settings/sync')} title={s.lastSyncAt ? `Last synced ${timeAgo(s.lastSyncAt)}` : 'Not synced yet'} aria-label={`Sync status: ${text}`}>
      {icon}{!compact && <span>{text}</span>}
    </button>
  );
}

function ReauthModal() {
  const sess = useSession();
  const [pw, setPw] = useState(''); const [err, setErr] = useState<string | null>(null); const [busy, setBusy] = useState(false);
  if (!sess.reauth) return null;
  const submit = async () => {
    setBusy(true); setErr(null);
    try { await reauthenticate(pw); setPw(''); toast.success('Signed in again. Syncing your changes.'); }
    catch (e) { setErr((e as Error).message); } finally { setBusy(false); }
  };
  return (
    <Modal open onClose={() => {}} size="narrow" dismissable={false} title="Sign in to continue syncing" footer={<><Button onClick={() => logout(false)}>Sign out</Button><Button variant="primary" loading={busy} onClick={submit}>Sign in</Button></>}>
      <p className="muted">Your server session ended. Your work is safe on this device; enter your password to resume syncing.</p>
      <form onSubmit={(e) => { e.preventDefault(); void submit(); }}><Field label="Password" error={err}><PasswordInput autoFocus value={pw} onChange={(e) => setPw(e.target.value)} autoComplete="current-password" /></Field></form>
    </Modal>
  );
}

function SignOutModal({ open, onClose }: { open: boolean; onClose: () => void }) {
  const [wipe, setWipe] = useState(false);
  const s = useSyncStatus();
  const pending = s.pending + s.uploads;
  return (
    <Modal open={open} onClose={onClose} size="narrow" title="Sign out" footer={<><Button onClick={onClose}>Cancel</Button><Button variant="danger" onClick={() => void logout(wipe)} icon={<LogOut />}>Sign out</Button></>}>
      {pending > 0 && <div className="alert warn"><AlertTriangle />{plural(pending, 'change')} on this device have not synced yet. {wipe ? 'They will be lost.' : 'They stay encrypted on this device and sync next time you sign in.'}</div>}
      <Checkbox checked={wipe} onChange={setWipe} label={<span><span className="strong">Also remove offline data from this device</span><br /><span className="small muted">Recommended on shared or borrowed devices.</span></span>} />
    </Modal>
  );
}


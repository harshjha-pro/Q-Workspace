function MoreSheet({ open, onClose, onSignOut }: { open: boolean; onClose: () => void; onSignOut: () => void }) {
  const nav = useNavigate();
  const go = (to: string) => { onClose(); nav(to); };
  const s = useSyncStatus();
  const items: { label: string; icon: ReactNode; to?: string; onClick?: () => void; danger?: boolean }[] = [
    { label: 'Collections', icon: <ListOrdered />, to: '/collections' },
    { label: 'Favourites & pinned', icon: <Star />, to: '/favourites' },
    { label: 'Attachment Vault', icon: <Archive />, to: '/vault' },
    { label: 'Bulk import prompts', icon: <Upload />, to: '/import' },
    { label: s.authRequired ? 'Sign in to sync' : s.online ? `Sync · ${s.pending + s.uploads ? `${s.pending + s.uploads} pending` : 'up to date'}` : 'Offline · view sync', icon: <RefreshCw />, to: '/settings/sync' },
    { label: 'Settings', icon: <Settings />, to: '/settings' },
    { label: 'Lock now', icon: <Lock />, onClick: () => { onClose(); void lock('Workspace locked.'); } },
    { label: 'Sign out', icon: <LogOut />, danger: true, onClick: () => { onClose(); onSignOut(); } },
  ];
  return (
    <Modal open={open} onClose={onClose} title="More">
      <div className="action-sheet">
        {items.map((i) => <button key={i.label} className={`menu-item${i.danger ? ' danger' : ''}`} onClick={() => (i.to ? go(i.to) : i.onClick?.())}>{i.icon}{i.label}</button>)}
      </div>
    </Modal>
  );
}

function BottomNav({ onMore }: { onMore: () => void }) {
  const s = useSyncStatus();
  const loc = useLocation();
  const moreActive = ['/collections', '/favourites', '/import', '/settings'].some((p) => loc.pathname.startsWith(p));
  return (
    <nav className="bottom-nav" aria-label="Main navigation">
      <NavLink to="/" end className={({ isActive }) => (isActive ? 'active' : '')}><LayoutDashboard />Home</NavLink>
      <NavLink to="/projects" className={({ isActive }) => (isActive || loc.pathname.startsWith('/p/') ? 'active' : '')}><FolderKanban />Projects</NavLink>
      <NavLink to="/search" className={({ isActive }) => (isActive ? 'active' : '')}><Search />Search</NavLink>
      <NavLink to="/library" className={({ isActive }) => (isActive ? 'active' : '')}><Library />Library</NavLink>
      <button onClick={onMore} className={moreActive ? 'active' : ''} aria-label="More">{(!s.online || s.authRequired || s.conflicts > 0) && <span className="badge-dot" />}<MoreHorizontal />More</button>
    </nav>
  );
}

function Banners() {
  const s = useSyncStatus();
  const nav = useNavigate();
  const failed = [...store.pendingFiles.values()].filter((p) => p.status === 'error');
  return (
    <>
      {!s.online && <div className="banner warn" role="status"><CloudOff />You are offline. Changes are saved on this device and will sync automatically.</div>}
      {s.conflicts > 0 && <div className="banner err"><GitMerge />{plural(s.conflicts, 'item was', 'items were')} edited on two devices.<Button size="sm" variant="ghost" onClick={() => nav('/settings/sync')}>Review</Button></div>}
      {failed.length > 0 && <div className="banner err"><AlertTriangle />{plural(failed.length, 'upload')} failed: {failed[0].error}<Button size="sm" variant="ghost" onClick={() => nav('/settings/sync')}>Details</Button></div>}
    </>
  );
}

export default function AppShell() {
  const mobile = useIsMobile();
  const m = usePageMetaValue();
  const nav = useNavigate();
  const loc = useLocation();
  const [more, setMore] = useState(false);
  const [signOut, setSignOut] = useState(false);
  useEffect(() => { window.scrollTo(0, 0); }, [loc.pathname]);
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if ((e.metaKey || e.ctrlKey) && e.key.toLowerCase() === 'k') { e.preventDefault(); nav('/search'); }
    };
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, [nav]);
  useEffect(() => store.onEvent((e) => {
    if (e.type === 'conflict') toast.warn('This item was also changed on another device. Your version was kept for review.', { label: 'Review', onClick: () => nav('/settings/sync') });
    if (e.type === 'error') toast.error(e.message);
    if (e.type === 'restored') toast.info('The workspace was restored from a backup. Refreshing your local copy…');
  }), [nav]);

  const back = () => (typeof m.back === 'string' ? nav(m.back) : nav(-1));
  return (
    <div className="app">
      {!mobile && <Sidebar />}
      <div className="main">
        <header className="topbar">
          {mobile ? (
            <>
              {m.back ? <IconButton label="Back" icon={<ArrowLeft />} onClick={back} /> : <span className="brand-mark" style={{ width: 30, height: 30, marginRight: 6 }}><Layers3 style={{ width: 17, height: 17, color: '#fff' }} /></span>}
              <div className="mobile-title truncate">{m.title || 'Prompt Manager'}</div>
              <SyncPill compact />
              <IconButton label="Create" icon={<Plus />} onClick={() => openQuick('prompt')} className="hide" />
            </>
          ) : (
            <>
              <button className="search-trigger" onClick={() => nav('/search')}><Search />Search everything…<kbd>Ctrl K</kbd></button>
              <div className="grow" />
              <SyncPill />
              <NewMenu />
              <AccountMenu onSignOut={() => setSignOut(true)} />
            </>
          )}
        </header>
        <Banners />
        <main className="content" id="main"><Outlet /></main>
      </div>
      {mobile && <BottomNav onMore={() => setMore(true)} />}
      <MoreSheet open={more} onClose={() => setMore(false)} onSignOut={() => setSignOut(true)} />
      <SignOutModal open={signOut} onClose={() => setSignOut(false)} />
      <QuickHost />
      <ReauthModal />
    </div>
  );
}


function Sidebar() {
  useStoreVersion();
  const sess = useSession();
  const pinned = topProjects().filter((p) => p.pinned).slice(0, 6);
  const pinnedSubs = store.all('projects').filter((p) => p.parent_id && p.pinned && !p.archived).slice(0, 4);
  return (
    <aside className="sidebar" aria-label="Main navigation">
      <Link to="/" className="brand"><span className="brand-mark"><Layers3 /></span><span>Prompt Manager</span></Link>
      {NAV.map((n) => <NavLink key={n.to} to={n.to} end={n.end} className={({ isActive }) => `nav-item${isActive ? ' active' : ''}`} title={n.label}>{n.icon}<span className="nav-label">{n.label}</span></NavLink>)}
      {(pinned.length > 0 || pinnedSubs.length > 0) && <div className="nav-section">Pinned</div>}
      {[...pinned, ...pinnedSubs].map((p) => <NavLink key={p.id} to={`/p/${p.id}`} className={({ isActive }) => `nav-item nav-sub${isActive ? ' active' : ''}`} style={{ paddingLeft: 10 }} title={p.name}><Pin style={{ width: 14, height: 14 }} /><span className="nav-label truncate">{p.name}</span></NavLink>)}
      <div className="sidebar-foot">
        <NavLink to="/settings" className={({ isActive }) => `nav-item${isActive ? ' active' : ''}`} title="Settings"><Settings /><span className="nav-label">Settings</span></NavLink>
        <div className="storage-meter">
          <div className="row between"><span className="row gap-4"><ShieldCheck style={{ width: 14, height: 14 }} />{sess.storageMode === 'cloud' ? 'Private cloud' : sess.storageMode === 'self_hosted' ? 'Self-hosted' : 'Local only'}</span></div>
          <div className="tiny" style={{ opacity: .75, marginTop: 4 }}>{store.all('projects').length} projects · {store.all('files').length} files</div>
        </div>
      </div>
    </aside>
  );
}

